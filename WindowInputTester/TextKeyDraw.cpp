#include "StandardLib/ClassDefines.h"
#include "KeyboardCanvasDraw.h"
#include "TextKeyDraw.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTextKeyDraw::Init(const char* szText)
{
	PreInit();

	CKeyDraw::Init();
	mszText.Init(szText);

	PostInit();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTextKeyDraw::Class(void)
{
	CKeyDraw::Class();
	U_String(mszText);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTextKeyDraw::Free(void)
{
	mszText.Kill();
	CKeyDraw::Free();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTextKeyDraw::Draw(CImageDraw* pcDraw, CKeyboardCanvasDraw* pcKeyboardDraw, float64 fLeft, float64 fTop, float64 fRight, float64 fBottom)
{
	pcKeyboardDraw->DrawText(pcDraw, mszText.Text(), (int32)((fLeft + fRight) / 2), (int32)((fTop + fBottom) / 2));
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CTextKeyDraw::GetText(void) { return mszText.Text(); }
